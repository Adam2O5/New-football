List<List<String>> randomUnits(Random random, int size) {
  final length = 1 + random.nextInt(size.clamp(1, 12));
  return [
    for (var index = 0; index < length; index++)
      latinUnits[random.nextInt(latinUnits.length)],
  ];
}

String render(
  List<List<String>> units,
  Random random, {
  required VariantMode mode,
  required bool uppercase,
}) {
  final body = StringBuffer();
  for (final variants in units) {
    final value = switch (mode) {
      VariantMode.ascii => variants.first,
      VariantMode.accented =>
        variants.length == 1
            ? variants.first
            : variants[1 + random.nextInt(variants.length - 1)],
      VariantMode.mixed => variants[random.nextInt(variants.length)],
    };
    body.write(value);
  }

  final rendered = uppercase ? body.toString().toUpperCase() : body.toString();
  return '${outerWhitespace(random)}$rendered${outerWhitespace(random)}';
}

String outerWhitespace(Random random) {
  const whitespace = <String>[' ', '\t', '\n', '\r', '\u00a0'];
  final count = 1 + random.nextInt(3);
  return List<String>.generate(
    count,
    (_) => whitespace[random.nextInt(whitespace.length)],
  ).join();
}

String whitespaceOnly(Random random, int size) {
  const whitespace = <String>[' ', '\t', '\n', '\r', '\u00a0'];
  final count = 1 + random.nextInt(size.clamp(1, 12));
  return List<String>.generate(
    count,
    (_) => whitespace[random.nextInt(whitespace.length)],
  ).join();
}

/// Independent oracle for trim over every whitespace character generated by
/// this test. It intentionally does not call SaveNamePolicy.trimName.
String oracleTrim(String input) {
  var start = 0;
  var end = input.length;
  while (start < end && isOracleWhitespace(input.codeUnitAt(start))) {
    start++;
  }
  while (end > start && isOracleWhitespace(input.codeUnitAt(end - 1))) {
    end--;
  }
  return input.substring(start, end);
}

bool isOracleWhitespace(int codeUnit) => switch (codeUnit) {
  0x09 || 0x0a || 0x0d || 0x20 || 0x00a0 => true,
  _ => false,
};

/// Independent Name_Key oracle: trim, Unicode case folding supplied by Dart,
/// then explicit Latin/Polish canonicalization and combining-mark removal.
String oracleNameKey(String input) {
  final trimmed = oracleTrim(input);
  if (trimmed.isEmpty) {
    throw ArgumentError.value(input, 'input');
  }

  final lowered = trimmed.toLowerCase();
  final result = StringBuffer();
  for (final rune in lowered.runes) {
    if (isOracleCombiningMark(rune)) continue;
    result.write(oracleReplacements[rune] ?? String.fromCharCode(rune));
  }
  return result.toString();
}

bool isOracleCombiningMark(int rune) =>
    (rune >= 0x0300 && rune <= 0x036f) ||
    (rune >= 0x1ab0 && rune <= 0x1aff) ||
    (rune >= 0x1dc0 && rune <= 0x1dff) ||
    (rune >= 0x20d0 && rune <= 0x20ff) ||
    (rune >= 0xfe20 && rune <= 0xfe2f);

